// accents are drawn two rows above the base glyph
const ACUTE = ["...#.", "..#.."];
const TILDE = [".##.#", "#..#."];
const DIAER = [".#.#.", "....."];
const ACCENTS = {
  "Á": ["A", ACUTE], "É": ["E", ACUTE], "Í": ["I", ACUTE], "Ó": ["O", ACUTE], "Ú": ["U", ACUTE],
  "Ñ": ["N", TILDE], "Ü": ["U", DIAER],
};

export const GLYPH_W = 5;
export const GLYPH_H = 7;

const norm = (ch) => {
  const up = ch.toUpperCase();
  if (G[up] || ACCENTS[up]) return up;
  return " ";
};

export function textWidth(text, scale = 1) {
  let n = 0;
  for (const ch of String(text)) n += norm(ch) === " " ? 3 : GLYPH_W + 1;
  return Math.max(0, n - 1) * scale;
}

function paint(put, rows, x, y, scale) {
  for (let j = 0; j < rows.length; j++) {
    for (let i = 0; i < rows[j].length; i++) {
      if (rows[j][i] === "#") put(x + i * scale, y + j * scale, scale);
    }
  }
}

/**
 * Draws text through a `put(x, y, size)` callback (one call per lit pixel block).
 * Returns the width in pixels.
 */
export function drawText(put, text, x, y, scale = 1) {
  let cx = x;
  for (const ch of String(text)) {
    const k = norm(ch);
    if (k === " ") { cx += 3 * scale; continue; }
    if (ACCENTS[k]) {
      const [base, mark] = ACCENTS[k];
      paint(put, G[base], cx, y, scale);
      paint(put, mark, cx, y - 2 * scale, scale);
    } else {
      paint(put, G[k], cx, y, scale);
    }
    cx += (GLYPH_W + 1) * scale;
  }
  return cx - x - scale;
}
